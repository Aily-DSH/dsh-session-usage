/**
 * Regenerate `lib/holidays.js` from the holiday table shipped with
 * `@linxin666/dsh-usage`, so the cost estimate here prices public holidays
 * exactly like the usage plugin already installed in the desktop profile.
 *
 * Usage: node tools/gen-holidays.mjs [path-to-holidays.ts]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const source = process.argv[2]
  || 'C:/Users/Administrator/.dsh/profiles/desktop/node_modules/@linxin666/dsh-usage/src/core/holidays.ts'

const text = fs.readFileSync(source, 'utf8')
const table = {}
const entryPattern = /"(\d{4})":\s*\[([\s\S]*?)\]/g
let match
while ((match = entryPattern.exec(text)) !== null) {
  const year = match[1]
  const dates = []
  const datePattern = /"(\d{4}-\d{2}-\d{2})"/g
  let date
  while ((date = datePattern.exec(match[2])) !== null) dates.push(date[1])
  if (dates.length > 0) table[year] = dates
}

const years = Object.keys(table).sort()
if (years.length === 0) throw new Error('no holiday years parsed from ' + source)

const body = years
  .map((year) => {
    const dates = table[year].map((d) => '    ' + JSON.stringify(d) + ',').join('\n')
    return '  ' + JSON.stringify(year) + ': [\n' + dates + '\n  ],'
  })
  .join('\n')

const output = `/**
 * Chinese public-holiday dates (Beijing calendar days) copied from
 * \`@linxin666/dsh-usage\` so this plugin prices DeepSeek peak/off-peak billing
 * from the same calendar. Generated by tools/gen-holidays.mjs — do not edit.
 */
export const CHINESE_PUBLIC_HOLIDAYS = {
${body}
}

/** Newest year the table covers; later years carry no holiday dates. */
export const HOLIDAY_TABLE_LAST_YEAR = ${years[years.length - 1]}
`

fs.writeFileSync(path.join(root, 'lib', 'holidays.js'), output)
console.log('wrote lib/holidays.js with years ' + years.join(','))
